// The ColdLight catalog: every token and every component, with what each is for, in one place a
// person or an AI reads before building a screen. It is generated from the sources (the token
// build's tokens.json and each component's <Name>.variants.ts), never written by hand:
//   ui/catalog.json  for tools and AIs;
//   ui/CATALOG.md    the same, for people.
// `--check` fails, naming the command to run, when either file differs from what the sources say.

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { pathToFileURL } from "node:url";
import type { BuiltToken } from "../tokens/build.ts";
import type { ComponentMeta, Level } from "../../src/coldlight/catalog/types.ts";

const UI = new URL("../../", import.meta.url);
const ROOT = new URL("src/coldlight/", UI);
const LEVELS: Level[] = ["primitive", "block", "template", "pattern"];

const RULES = [
  "Build a screen from ColdLight components; reach for a lower level only when no higher one fits.",
  "Style with tokens only: `var(--cl-…)` from the list below. stylelint refuses a literal colour, size, weight or font, and names the closest token.",
  "Give every component its words through props or snippets; no text is written inside a component.",
  "A level imports only from the levels below it: primitives, then blocks, templates and patterns.",
  "Each component folder holds <Name>.svelte, <Name>.variants.ts, <Name>.stories.svelte and <Name>.test.ts.",
];

interface Entry extends ComponentMeta {
  path: string;
}

function fail(message: string): never {
  console.error(`catalog: ${message}`);
  process.exit(1);
}

function tokens(): BuiltToken[] {
  try {
    return JSON.parse(readFileSync(new URL("tokens/build/tokens.json", ROOT), "utf8")) as BuiltToken[];
  } catch {
    fail("tokens/build/tokens.json is missing; run `npm run catalog`, which builds the tokens first");
  }
}

async function components(): Promise<Entry[]> {
  const root = new URL(".", ROOT).pathname.replace(/^\/([A-Za-z]:)/, "$1");
  const files = readdirSync(root, { recursive: true, encoding: "utf8" })
    .map((file) => file.replaceAll("\\", "/"))
    .filter((file) => /(^|\/)([A-Z][A-Za-z]+)\/\2\.variants\.ts$/.test(file))
    .sort();
  const entries: Entry[] = [];
  for (const file of files) {
    const module = (await import(pathToFileURL(join(root, file)).href)) as { meta?: ComponentMeta };
    if (!module.meta) fail(`${file} exports no \`meta\`; every <Name>.variants.ts exports one (catalog/types.ts)`);
    entries.push({ ...module.meta, path: relative(new URL(".", UI).pathname.replace(/^\/([A-Za-z]:)/, "$1"), join(root, file)).replaceAll("\\", "/").replace(/\/[^/]+$/, "/") });
  }
  return entries.sort((a, b) => LEVELS.indexOf(a.level) - LEVELS.indexOf(b.level) || a.name.localeCompare(b.name));
}

function cell(text: string): string {
  return text.replaceAll("|", "\\|").replaceAll("\n", " ");
}

function markdown(list: BuiltToken[], entries: Entry[]): string {
  const out = [
    "# The ColdLight catalog",
    "",
    "Generated by `npm run catalog` from the token sources and each component's `<Name>.variants.ts`. Do not edit.",
    "The same data, for tools and AIs, is in [catalog.json](catalog.json).",
    "",
    "## How to build a screen",
    "",
    ...RULES.map((rule) => `- ${rule}`),
    "",
    "## Components",
    "",
  ];
  for (const level of LEVELS) {
    const here = entries.filter((entry) => entry.level === level);
    if (!here.length) continue;
    out.push(`### ${level[0]?.toUpperCase()}${level.slice(1)}s`, "");
    for (const entry of here) {
      out.push(`#### ${entry.name}`, "", `${entry.summary} [${entry.path}](${entry.path})`, "", `**Use:** ${entry.use}`);
      if (entry.avoid) out.push("", `**Instead:** ${entry.avoid}`);
      out.push("", "```svelte", entry.example, "```", "");
      for (const [axis, variant] of Object.entries(entry.variants)) {
        out.push(`**${axis}** (default \`${variant.default}\`): ${variant.description}`, "");
        for (const [value, meaning] of Object.entries(variant.values)) out.push(`- \`${value}\`: ${meaning}`);
        out.push("");
      }
      out.push("| Prop | Type | |", "|---|---|---|");
      for (const prop of entry.props) {
        out.push(`| \`${prop.name}\`${prop.required ? " (required)" : ""} | \`${cell(prop.type)}\` | ${cell(prop.description)} |`);
      }
      out.push("", `**Accessibility:** ${entry.a11y}`, "");
    }
  }
  for (const layer of ["semantic", "composite"] as const) {
    out.push(`## ${layer === "semantic" ? "Tokens: roles" : "Tokens: composites"}`, "", "| Token | Use it for | Light | Dark |", "|---|---|---|---|");
    for (const token of list.filter((t) => t.layer === layer)) {
      out.push(`| \`var(${token.css})\` | ${cell(token.description)} | \`${cell(token.value)}\` | ${token.dark ? `\`${cell(token.dark)}\`` : "same"} |`);
    }
    out.push("");
  }
  return out.join("\n");
}

const list = tokens();
const entries = await components();
const files = {
  "catalog.json": `${JSON.stringify({ generatedBy: "ui/scripts/catalog/build.ts", rules: RULES, components: entries, tokens: list }, null, 2)}\n`,
  "CATALOG.md": markdown(list, entries),
};

if (process.argv.includes("--check")) {
  const stale = Object.entries(files).filter(([name, text]) => {
    try {
      return readFileSync(new URL(name, UI), "utf8").replaceAll("\r\n", "\n") !== text;
    } catch {
      return true;
    }
  });
  if (stale.length) {
    fail(`${stale.map(([name]) => `ui/${name}`).join(" and ")} differ from the sources; run \`npm run catalog\` in ui/ and commit the result`);
  }
  console.log(`catalog: up to date (${entries.length} components, ${list.length} tokens)`);
} else {
  for (const [name, text] of Object.entries(files)) writeFileSync(new URL(name, UI), text);
  console.log(`catalog: wrote ui/catalog.json and ui/CATALOG.md (${entries.length} components, ${list.length} tokens)`);
}
